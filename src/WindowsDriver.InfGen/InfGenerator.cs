using WindowsDriver.InfGen;

namespace WindowsDriver.InfGen;

/// <summary>
/// Generates a driver INF from a <see cref="DriverManifest"/>. The output
/// follows the Windows INF grammar: Version block, per-architecture manufacturer
/// and DDInstall sections, source disks, destination dirs, the WDF install
/// section (UmdfService or KmdfService) and the strings table.
/// </summary>
public sealed class InfGenerator
{
    private readonly string _generationDate;

    public InfGenerator(DateOnly? generationDate = null)
    {
        _generationDate = generationDate?.ToString("MM/dd/yyyy")
                          ?? DateOnly.FromDateTime(DateTime.UtcNow).ToString("MM/dd/yyyy");
    }

    /// <summary>Generates the INF text for the given architectures (default amd64 + arm64).</summary>
    public string Generate(DriverManifest manifest, IReadOnlyList<string>? architectures = null)
    {
        DriverManifest.Validate(manifest);
        var arches = architectures ?? ["NTamd64", "NTarm64"];
        var serviceName = manifest.ServiceName ?? manifest.Name;
        var manufacturer = manifest.Manufacturer ?? manifest.Provider;
        var catalog = manifest.CatalogFile ?? $"{manifest.Name}.cat";
        var driverBinary = manifest.Files[0].Source;
        var date = manifest.DriverVerDate ?? _generationDate;

        var lines = new List<string>
        {
            $"; Generated by infgen {SdkVersion} — do not edit by hand.",
            $"; Source manifest: {manifest.Name} ({manifest.Framework} driver, v{manifest.Version}).",
            string.Empty,
            "[Version]",
            "Signature=\"$WINDOWS NT$\"",
            $"Class={manifest.Class}",
            $"ClassGuid={NormalizeGuid(manifest.ClassGuid)}",
            "Provider=%Provider%",
            $"CatalogFile={catalog}",
            $"DriverVer={date},{manifest.Version}",
            "PnpLockdown=1",
            string.Empty,
            "[Manufacturer]",
            "%Manufacturer%=Standard," + string.Join(",", arches),
            string.Empty,
        };

        foreach (var arch in arches)
        {
            var install = $"Install.{arch}";
            lines.Add($"[Standard.{arch}]");
            for (var m = 0; m < manifest.Models.Count; m++)
            {
                var model = manifest.Models[m];
                var ids = string.Join(",", model.HardwareIds.Concat(model.CompatibleIds).Select(EscapeHwId));
                lines.Add($"%Model{m}%={install},{ids}");
            }
            lines.Add(string.Empty);
            lines.Add($"[{install}]");
            lines.Add("CopyFiles=DriverFiles");
            lines.Add(string.Empty);
            lines.Add($"[{install}.Wdf]");
            if (manifest.Framework == DriverFramework.Umdf)
            {
                lines.Add($"UmdfService={serviceName}, {serviceName}_Install");
                lines.Add($"UmdfServiceOrder={serviceName}");
                lines.Add(string.Empty);
                lines.Add($"[{serviceName}_Install]");
                lines.Add($"UmdfLibraryVersion={manifest.WdfLibraryVersion ?? "2.15.0"}");
                lines.Add($"ServiceBinary=%12%\\{driverBinary}");
            }
            else
            {
                lines.Add($"KmdfService={serviceName}, {serviceName}_Install");
                lines.Add(string.Empty);
                lines.Add($"[{serviceName}_Install]");
                lines.Add($"KmdfLibraryVersion={manifest.WdfLibraryVersion ?? "1.15"}");
            }
            lines.Add(string.Empty);
        }

        lines.Add("[DriverFiles]");
        foreach (var file in manifest.Files)
        {
            lines.Add(file.Source);
        }
        lines.Add(string.Empty);
        lines.Add("[SourceDisksNames]");
        lines.Add("1 = %DiskName%");
        lines.Add(string.Empty);
        lines.Add("[SourceDisksFiles]");
        foreach (var file in manifest.Files)
        {
            lines.Add($"{file.Source} = 1");
        }
        lines.Add(string.Empty);
        lines.Add("[DestinationDirs]");
        lines.Add("DriverFiles = 12 ; %windir%\\system32\\drivers");
        lines.Add(string.Empty);
        lines.Add("[Strings]");
        lines.Add($"Provider = \"{manifest.Provider}\"");
        lines.Add($"Manufacturer = \"{manufacturer}\"");
        for (var m = 0; m < manifest.Models.Count; m++)
        {
            lines.Add($"Model{m} = \"{manifest.Models[m].Name}\"");
        }
        lines.Add("DiskName = \"Windows Driver SDK installation media\"");

        return string.Join(Environment.NewLine, lines) + Environment.NewLine;
    }

    public static string NormalizeGuid(string guid)
    {
        guid = guid.Trim();
        if (!guid.StartsWith('{'))
        {
            guid = "{" + guid;
        }
        if (!guid.EndsWith('}'))
        {
            guid += "}";
        }
        return guid.ToLowerInvariant();
    }

    private static string EscapeHwId(string id) => id.Replace('"', '\'');

    public const string SdkVersion = "0.1.0-preview.1";
}
